"""Builds a clean, production-style Fabric 1.21.11 client profile for private validation of the release jar.

Usage: make_profile.py <profile-dir> <mods...>

Nothing from the development environment is used: the game runs from Mojang's obfuscated client jar, Fabric Loader
remaps it to intermediary at first launch exactly as in a normal installation, and mods/ holds only published jars.
Libraries come from the local Gradle cache when present (same files Mojang publishes), otherwise from Mojang's
library URLs listed in the version manifest. Writes <profile-dir>/launch.sh (Java 21, offline account).
"""
import glob
import hashlib
import json
import os
import platform
import shutil
import sys
import urllib.request

HOME = os.path.expanduser("~")
LOOM = os.path.join(HOME, ".gradle/caches/fabric-loom")
M2 = os.path.join(HOME, ".gradle/caches/modules-2/files-2.1")
VERSION = "1.21.11"

out = os.path.abspath(sys.argv[1])
mods = sys.argv[2:]
info = json.load(open(os.path.join(LOOM, VERSION, "mojang_minecraft_info.json")))
arch = "arm64" if platform.machine() == "arm64" else "x86_64"


def allowed(lib):
    rules = lib.get("rules")
    if not rules:
        return True
    ok = False
    for r in rules:
        osr = r.get("os", {})
        match = (not osr) or (osr.get("name") == "osx" and ("arch" not in osr or osr["arch"] == arch))
        if match:
            ok = r["action"] == "allow"
    return ok


def cached(group, artifact, version, classifier=None):
    name = f"{artifact}-{version}" + (f"-{classifier}" if classifier else "") + ".jar"
    hits = glob.glob(os.path.join(M2, group, artifact, version, "*", name))
    return hits[0] if hits else None


libdir = os.path.join(out, "libraries")
os.makedirs(libdir, exist_ok=True)
classpath, missing = [], []
for lib in info["libraries"]:
    if not allowed(lib):
        continue
    parts = lib["name"].split(":")
    group, artifact, version = parts[0], parts[1], parts[2]
    classifier = parts[3] if len(parts) > 3 else None
    path = cached(group, artifact, version, classifier)
    if path is None:
        art = lib.get("downloads", {}).get("artifact")
        if not art:
            missing.append(lib["name"])
            continue
        dest = os.path.join(libdir, os.path.basename(art["path"]))
        if not os.path.exists(dest):
            urllib.request.urlretrieve(art["url"], dest)
        if hashlib.sha1(open(dest, "rb").read()).hexdigest() != art["sha1"]:
            sys.exit("sha1 mismatch for " + lib["name"])
        path = dest
    classpath.append(path)

# Fabric Loader and its own libraries (from the loader's fabric-installer.json), plus intermediary mappings
loader = cached("net.fabricmc", "fabric-loader", "0.19.5")
for n in ["org.ow2.asm:asm:9.10.1", "org.ow2.asm:asm-analysis:9.10.1", "org.ow2.asm:asm-commons:9.10.1",
          "org.ow2.asm:asm-tree:9.10.1", "org.ow2.asm:asm-util:9.10.1", "net.fabricmc:sponge-mixin:0.17.4+mixin.0.8.7"]:
    g, a, v = n.split(":")
    p = cached(g, a, v)
    if p is None:
        missing.append(n)
    else:
        classpath.append(p)
classpath.insert(0, loader)
inter = glob.glob(os.path.join(M2, "net.fabricmc", "intermediary", VERSION, "*", f"intermediary-{VERSION}-v2.jar"))[0]
classpath.append(inter)
client = os.path.join(out, "versions", VERSION, f"{VERSION}.jar")
os.makedirs(os.path.dirname(client), exist_ok=True)
shutil.copy2(os.path.join(LOOM, VERSION, "minecraft-client.jar"), client)
classpath.append(client)
if missing:
    sys.exit("missing libraries: " + ", ".join(missing))

game = os.path.join(out, "game")
os.makedirs(os.path.join(game, "mods"), exist_ok=True)
for m in mods:
    shutil.copy2(m, os.path.join(game, "mods", os.path.basename(m)))

java = os.popen("/usr/libexec/java_home -v 21").read().strip() + "/bin/java"
assets = os.path.join(LOOM, "assets")
# Loom stores the index as <version>-<id>.json; use whichever name exists
index_id = info["assetIndex"]["id"]
if not os.path.exists(os.path.join(assets, "indexes", index_id + ".json")) and os.path.exists(os.path.join(assets, "indexes", f"{VERSION}-{index_id}.json")):
    index_id = f"{VERSION}-{index_id}"
launch = os.path.join(out, "launch.sh")
with open(launch, "w") as f:
    f.write("#!/usr/bin/env bash\n# Production-style launch (Java 21, offline account). Generated by make_profile.py.\n")
    f.write(f'cd "{game}"\n')
    f.write(f'exec "{java}" -XstartOnFirstThread -Xmx3G $JVM_OPTS -cp "{":".join(classpath)}" net.fabricmc.loader.impl.launch.knot.KnotClient '
            f'--username Tester --version fabric-loader-0.19.5-{VERSION} --gameDir "{game}" --assetsDir "{assets}" '
            f'--assetIndex {index_id} --uuid 00000000000000000000000000000001 --accessToken 0 --versionType release "$@"\n')
os.chmod(launch, 0o755)
print(json.dumps({"profile": out, "java": java, "classpathEntries": len(classpath), "mods": sorted(os.listdir(os.path.join(game, "mods")))}, indent=1))
